// The paths are kept exactly as Phosphor draws them, in a 256x256 box: four line weights (thin, light,
// regular, bold) for the outline, fill for solid, and the tint layer of Phosphor's duotone. A duotone
// icon is the regular outline over that tint, so all three styles stay the same drawing (Phosphor's own
