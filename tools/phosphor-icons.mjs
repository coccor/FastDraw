const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/phosphor-icons.mjs <phosphor assets folder>'); process.exit(1); }
const names = Object.keys(MAP).sort();
const read = (weight, name) => {
  const file = path.join(dir, weight, `${MAP[name]}${weight === 'regular' ? '' : '-' + weight}.svg`);
  const svg = fs.readFileSync(file, 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"( opacity="([\d.]+)")?/g)].map((m) => ({ d: m[1], tint: !!m[2] }));
  if (!paths.length) throw new Error(`no path in ${file}`);
  return paths;
};
const table = (fn) => names.map((n) => `    ${JSON.stringify(n)}: ${JSON.stringify(fn(n))},`).join('\n');
const weights = ['thin', 'light', 'regular', 'bold', 'fill'].map((w) => `  ${w}: {\n${table((n) => read(w, n).map((p) => p.d))}\n  },`).join('\n');
const tints = table((n) => read('duotone', n).filter((p) => p.tint).map((p) => p.d)).replace(/^    /gm, '  ');
const out = `// Generated by tools/phosphor-icons.mjs; do not edit by hand.
// Every built-in icon in each style, from Phosphor Icons (https://phosphoricons.com, MIT licence,
// copyright (c) 2023 Phosphor Icons), drawn as filled shapes in a 256x256 box. The outline comes in four
// line weights; solid is Phosphor's fill; duotone is the regular outline over the tint here.
export const ICON_BOX = 256;
export type IconWeight = 'thin' | 'light' | 'regular' | 'bold' | 'fill';
// the outline's line width in each weight, in the 256 box
export const WEIGHT_WIDTH: Record<Exclude<IconWeight, 'fill'>, number> = { thin: 4, light: 12, regular: 16, bold: 24 };
export const ICON_WEIGHTS: Record<IconWeight, Record<string, string[]>> = {
${weights}
};
export const DUOTONE_TINT: Record<string, string[]> = {
${tints}
};
`;
fs.writeFileSync(new URL('../src/iconSet.ts', import.meta.url), out);
console.log(`wrote ${names.length} icons in 5 weights and duotone`);
