"""Builds src/duotoneIcons.ts: the tinted part of each built-in icon's duotone style.

A duotone icon is its outline drawn in full colour over a light tint of the same colour. The tint fills
the icon's main enclosed parts: the regions its own lines close off, the largest of them and any of a
similar size (a gear's ring, not its small centre hole). It is made from the outline itself, in the same
24x24 box, so the two always line up. An icon that encloses nothing (an arrow, a line chart) has no tint
and its duotone is the outline alone.

  python3 -m venv .venv && .venv/bin/pip install shapely svgpathtools
  node -e "import('./src/icons.ts').then(m => console.log(JSON.stringify(m.ICONS)))" > /tmp/icons.json
  .venv/bin/python tools/duotone-icons.py /tmp/icons.json
"""
import json, sys
from pathlib import Path
from svgpathtools import parse_path
from shapely.geometry import LineString, Polygon, MultiPolygon, box
from shapely.ops import unary_union
from shapely.geometry.polygon import orient

STROKE = 1.5   # the outline icons' line width
KEEP = 0.3     # a region is a main part when it is at least this share of the largest one
MIN_AREA = 3   # smaller regions (an eye's pupil, a lock's keyhole) stay untinted
# people: the body's line is open along the bottom; close it, so the whole figure is tinted
CLOSE = {'admin', 'team', 'user', 'users'}
# encloses nothing, but reads as one shape: tint the area its lines span (wifi's wedge)
HULL = {'wifi'}


def lines_of(d, close=False):
    """the outline's strokes, as polylines sampled along each subpath"""
    out = []
    for sub in parse_path(d).continuous_subpaths():
        if not len(sub): continue
        n = max(8, int(sub.length() * 4))
        pts = [sub.point(i / n) for i in range(n + 1)]
        pts = [(p.real, p.imag) for p in pts]
        if close and pts[0] != pts[-1]: pts.append(pts[0])
        out.append(LineString(pts) if len(set(pts)) > 1 else None)
    return [l for l in out if l is not None]


def tint(name, paths):
    lines = [l for d in paths for l in lines_of(d, name in CLOSE)]
    if not lines: return None
    if name in HULL:
        return unary_union(lines).convex_hull.simplify(0.02)
    strokes = unary_union([l.buffer(STROKE / 2, quad_segs=8) for l in lines])
    # the faces: what is left of the plane once the strokes are drawn, without the outside
    rest = box(-2, -2, 26, 26).difference(strokes)
    faces = [f for f in (rest.geoms if isinstance(rest, MultiPolygon) else [rest]) if not f.touches(box(-2, -2, 26, 26).exterior) and f.bounds[0] > -2 and f.bounds[2] < 26]
    faces = [f for f in faces if f.area >= MIN_AREA]
    if not faces: return None
    top = max(f.area for f in faces)
    keep = [f for f in faces if f.area >= KEEP * top]
    # grow each kept face to the middle of its lines, so the outline covers its edge
    return unary_union([f.buffer(STROKE / 2, quad_segs=8, join_style='mitre') for f in keep]).simplify(0.02)


def to_path(g):
    polys = list(g.geoms) if isinstance(g, MultiPolygon) else [g]
    out = []
    for p in polys:
        p = orient(p, 1.0)
        for ring in [p.exterior, *p.interiors]:
            c = list(ring.coords)[:-1]
            out.append('M' + 'L'.join(f'{round(x, 2):g} {round(y, 2):g}' for x, y in c) + 'Z')
    return ''.join(out)


icons = json.load(open(sys.argv[1]))
rows, bare = [], []
for name in sorted(icons):
    t = tint(name, icons[name])
    if t is None or t.is_empty: bare.append(name); continue
    rows.append(f'  {json.dumps(name)}: {json.dumps(to_path(t))},')
out = f"""// Generated by tools/duotone-icons.py; do not edit by hand.
// The tinted part of each built-in icon's duotone style (icon.style=duotone): its main enclosed regions,
// made from the outline in icons.ts, in the same 24x24 box. An icon missing here encloses nothing, so
// its duotone is the outline alone.
export const DUOTONE_ICONS: Record<string, string> = {{
{chr(10).join(rows)}
}};
"""
Path(__file__).resolve().parent.parent.joinpath('src/duotoneIcons.ts').write_text(out)
print(f'{len(rows)} tinted; outline only: {", ".join(bare)}')
