const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/solid-icons.mjs <phosphor assets/fill folder>'); process.exit(1); }
const lines = Object.keys(MAP).sort().map((name) => {
  if (OWN[name]) return `  ${JSON.stringify(name)}: ${JSON.stringify(OWN[name])},`;
  const svg = fs.readFileSync(path.join(dir, `${MAP[name]}-fill.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`no path in ${MAP[name]}`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(paths)},`;
});
