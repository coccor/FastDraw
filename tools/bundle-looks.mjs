// Writes src/bundledLooks.ts from looks/*.look, so the named looks ship inside FastDraw (CLI and
// editor alike) and a diagram can say `look sketch` without a file. Run after editing a look:
//   node tools/bundle-looks.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const NAMES = ['engraved', 'headline', 'keys', 'listing', 'night', 'offset', 'reference', 'shade', 'sketch', 'transit', 'whiteboard'];

export function generate(root = new URL('..', import.meta.url)) {
  const body = NAMES.map((n) => `  ${n}: ${JSON.stringify(readFileSync(new URL(`looks/${n}.look`, root), 'utf8'))},`).join('\n');
  return `// Generated by tools/bundle-looks.mjs from looks/*.look. Do not edit by hand.\nexport const BUNDLED_LOOKS: Record<string, string> = {\n${body}\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../src/bundledLooks.ts', import.meta.url), generate());
  console.log('wrote src/bundledLooks.ts');
}
